import pyttsx3, time
t0=time.time()
e=pyttsx3.init()
e.save_to_file('alpha beta gamma', 'generated/_p3.wav')
e.runAndWait()
print('first', round(time.time()-t0,1), flush=True)
t1=time.time()
e.save_to_file('delta epsilon zeta', 'generated/_p4.wav')
e.runAndWait()
print('second', round(time.time()-t1,1), flush=True)
t2=time.time()
e.save_to_file('eta theta iota', 'generated/_p5.wav')
e.runAndWait()
print('third', round(time.time()-t2,1), flush=True)
e.stop()
print('stopped', round(time.time()-t2,1), flush=True)
